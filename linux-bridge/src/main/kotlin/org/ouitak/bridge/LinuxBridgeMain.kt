// Stable across restarts so TAK Aware replaces markers instead of leaving ghosts.
internal fun stableHostname(): String {
    val raw = runCatching { Files.readString(Path.of("/etc/hostname")).trim() }.getOrNull()
        ?.takeIf { it.isNotEmpty() }
        ?: System.getenv("HOSTNAME")?.trim()?.takeIf { it.isNotEmpty() }
        ?: runCatching { java.net.InetAddress.getLocalHost().hostName }.getOrNull()
        ?: "unknown-host"
    return raw.lowercase().replace(Regex("[^a-z0-9.-]"), "-")
}

fun main(args: Array<String>) {
    try { bridgeMain(args) } catch (error: Exception) {
        val code=bridgeFailureCode(error)
        val action=bridgeFailureAction(code)
        if(args.firstOrNull()=="--dronk") println(org.ouitak.app.core.serial.DronkJson.encode(mapOf("kind" to "error","code" to code,"message" to action)))
        System.err.println("$code: $action Private details withheld.")
        kotlin.system.exitProcess(2)
    }
}

private fun bridgeMain(args: Array<String>) {
    if (args.firstOrNull() == "--dronk") { runDronkBridge(args.drop(1).toTypedArray()); return }
    val config = BridgeConfig.parse(args)
    val transport = if (config.forwardLive) tlsTransport(config) else null
    val sender = transport?.let { org.ouitak.app.core.QueuedCotForwarder(it, { tlsTransport(config) }) }
    val forwardingCot = org.ouitak.app.core.CotGenerator(config.staleAfter)
    val receiverNamespace = "linux-${stableHostname()}"
    var lastStatusAt = 0L
    val processor = LiveSerialProcessor(
        receiverNamespace = receiverNamespace,
        policy = { if (config.allowProvisional) LegacyAssociationPolicy.ALLOW_PROVISIONAL else LegacyAssociationPolicy.DISABLED },
        staleAfter = config.staleAfter,
        onProcessed = { result ->
            if (result.tracking is TrackUpdate.Updated) {
                val msg = result.detection
                val sourceLabel = if (msg.source == ObservationSource.SIMULATION) "SYNTHETIC" else "LIVE"
                log("$sourceLabel observation accepted identifierType=${msg.identifierType} " +
                    "coordinatesPresent=${msg.position != null} speedPresent=${msg.speedMps != null} headingPresent=${msg.headingDegrees != null} " +
                    "broadcastTime=unavailable receiverTime=${msg.receivedAt}")
                if (sender != null) {
                    val expiresAt=(result.tracking as TrackUpdate.Updated).track.expiresAt
                    sender.offer(forwardingCot.generateForForwarding(result.detection,config.forwardPilotLocation),expiresAt)
                    forwardingCot.generateGroundLocationsForForwarding(result.detection,config.forwardPilotLocation).forEach { sender.offer(it,expiresAt) }
                    val delivery=sender.snapshot()
                    log("CoT queued; attempts=${delivery.attempts} written=${delivery.written} failed=${delivery.failed} queueDrops=${delivery.queueDrops} pending=${delivery.queued} timeouts=${delivery.timeouts} code=${delivery.errorCode ?: "none"}")
                } else log("capture-only: CoT was generated by shared core and was not transmitted")
            } else {
                log("candidate not emitted: ${(result.tracking as TrackUpdate.Ignored).reason}")
            }
        },
        onDiagnostic = { event, counts ->
            val now = System.nanoTime()
            if (now - lastStatusAt >= 5_000_000_000L || event is SerialEvent.Rejected) {
                lastStatusAt = now
                val detail = when (event) {
                    is SerialEvent.Candidate -> {
                        val candidate = event.value
                        val fields = buildList {
                            if (candidate.mac != null) add("mac")
                            if (candidate.rssi != null) add("rssi")
                            if (candidate.aircraft.position != null || candidate.aircraft.validity.name == "INVALID") add("drone_lat/drone_long")
                            if (candidate.aircraft.position?.haeMeters != null) add("drone_altitude")
                            if (candidate.unresolvedPilot.position != null) add("pilot_lat/pilot_long")
                            if (candidate.basicId != null) add("basic_id")
                        }
                        "candidate-fields=${fields.joinToString(",")}"
                    }
                    is SerialEvent.Ignored -> "ignored:${event.reason}${event.detail?.let { ":$it" }.orEmpty()}"
                    is SerialEvent.Rejected -> "rejected:${event.reason}"
                }
                log("serial $detail accepted=${counts.accepted} ignored=${counts.ignored} rejected=${counts.rejected}")
            }
        }
    )

    val input = DataInputStream(System.`in`)
    log("bridge ready mode=${when { config.synthetic && transport != null -> "authenticated-TLS-synthetic"; config.synthetic -> "synthetic"; config.live -> "authenticated-TLS-live"; else -> "capture-only" }} " +
        "receiverNamespace=internal provisional=${config.allowProvisional}; " +
        "source=${if (config.synthetic) "explicit synthetic Sky Spy fixture" else "live OUI-SPY USB"}")
    if (transport != null) log("TLS transport status=${transport.status().message}")
    try {
        if (config.synthetic) {
            runSyntheticScenario(processor)
            return
        }
        while (true) {
            val kind = try { input.readUnsignedByte() } catch (_: java.io.EOFException) { break }
            when (kind) {
                CONNECTED -> log("USB CDC reader connected")
                DISCONNECTED -> {
                    processor.disconnected()
                    val stats = processor.diagnostics
                    log("USB CDC disconnected; partial frame discarded accepted=${stats.accepted} ignored=${stats.ignored} rejected=${stats.rejected}")
                }
                DATA -> {
                    val length = input.readInt()
                    require(length in 1..MAX_ENVELOPE) { "Invalid internal byte-chunk length" }
                    val bytes = ByteArray(length)
                    input.readFully(bytes)
                    processor.feed(bytes, SerialContext(Instant.now(), ObservationSource.OUI_SPY_USB))
                }
                STOP -> break
                STATUS -> {
                    val stats = processor.diagnostics
                    log("bridge heartbeat connected=true accepted=${stats.accepted} ignored=${stats.ignored} rejected=${stats.rejected} " +
                        "deliveryAttempts=${sender?.snapshot()?.attempts ?: 0} deliveredWrites=${sender?.snapshot()?.written ?: 0} failedWrites=${sender?.snapshot()?.failed ?: 0} " +
                        "tls=${sender?.snapshot()?.state ?: "not-configured"} queueDrops=${sender?.snapshot()?.queueDrops ?: 0} timeouts=${sender?.snapshot()?.timeouts ?: 0} code=${sender?.snapshot()?.errorCode ?: "none"}")
                }
                else -> throw IllegalArgumentException("Unknown internal serial-reader message")
            }
        }
    } finally {
        processor.disconnected()
        try { sender?.close() } catch (_: Exception) { }
        val stats = processor.diagnostics
        log("bridge stopped accepted=${stats.accepted} ignored=${stats.ignored} rejected=${stats.rejected} " +
            "deliveryAttempts=${sender?.snapshot()?.attempts ?: 0} deliveredWrites=${sender?.snapshot()?.written ?: 0} failedWrites=${sender?.snapshot()?.failed ?: 0} " +
            "mode=${when { config.synthetic && transport != null -> "authenticated-TLS-synthetic"; config.synthetic -> "synthetic"; config.live -> "authenticated-TLS-live"; else -> "capture-only" }}")
    }
}

internal data class BridgeConfig(
    val synthetic: Boolean,
    val live: Boolean,
    val forwardLive: Boolean,
    val forwardSynthetic: Boolean,
    val allowProvisional: Boolean,
    val staleAfter: java.time.Duration,
    val hostname: String,
    val port: Int,
    val p12: Path?,
    val passwordFile: Path?,
    val caFile: Path?,
    val connectAddress: String = hostname,
    val forwardPilotLocation: Boolean = false,
    /** How long a LAST KNOWN marker stays valid in TAK after it is reported. */
    val lastKnownRetention: java.time.Duration = java.time.Duration.ofSeconds(600),
    val lastKnownStyle: org.ouitak.app.core.LastKnownStyle = org.ouitak.app.core.LastKnownStyle.SPOT
) {
    companion object {
        fun parse(args: Array<String>, environment: Map<String,String> = System.getenv()): BridgeConfig {
            var synthetic = false
            var live = false
            var forwardLive = false
            var forwardSynthetic = false
            var provisional = true
            var stale = 60L
            var lastKnown = 600L
            var lastKnownStyle = org.ouitak.app.core.LastKnownStyle.SPOT
            var hostname = environment.get("DRONK_TAK_HOST").orEmpty()
            var connectAddress = environment.get("DRONK_TAK_CONNECT_ADDRESS")
            var port = environment.get("DRONK_TAK_PORT")?.let { it.toIntOrNull() ?: throw IllegalArgumentException("Invalid TAK port") } ?: 8089
            var p12: Path? = environment.get("DRONK_TAK_CLIENT_P12")?.let(Path::of)
            var password: Path? = environment.get("DRONK_TAK_PASSWORD_FILE")?.let(Path::of)
            var ca: Path? = environment.get("DRONK_TAK_CA_FILE")?.let(Path::of)
            var pilot = when (environment["DRONK_TAK_FORWARD_PILOT_LOCATION"]?.lowercase()) {
                null,"false" -> false; "true" -> true; else -> throw BridgeFailure("E_CONFIG")
            }
            var index = 0
            while (index < args.size) {
                when (val arg = args[index++]) {
                    "--capture-only" -> Unit
                    "--synthetic" -> synthetic = true
                    "--live" -> live = true
                    "--forward-live" -> forwardLive = true
                    "--forward-synthetic" -> forwardSynthetic = true
                    "--forward-pilot-location" -> pilot = true
                    "--no-forward-pilot-location" -> pilot = false
                    "--disable-provisional" -> provisional = false
                    "--stale-seconds" -> stale = args.value(index++).toLong()
                    "--last-known-seconds" -> lastKnown = args.value(index++).toLong()
                    "--last-known-style" -> lastKnownStyle = when (args.value(index++)) { "spot" -> org.ouitak.app.core.LastKnownStyle.SPOT
                        "same-type" -> org.ouitak.app.core.LastKnownStyle.SAME_TYPE; else -> throw IllegalArgumentException("Invalid last-known style") }
                    "--tak-host" -> hostname = args.value(index++)
                    "--tak-connect-address" -> connectAddress = args.value(index++)
                    "--tak-port" -> port = args.value(index++).toInt()
                    "--client-p12" -> p12 = Path.of(args.value(index++))
                    "--password-file" -> password = Path.of(args.value(index++))
                    "--ca-file" -> ca = Path.of(args.value(index++))
                    else -> throw IllegalArgumentException("Unknown bridge option; value withheld")
                }
            }
            require(stale in 5..3600 && port in 1..65535) { "Invalid stale interval or TAK endpoint" }
            require(lastKnown in 60..86400) { "Invalid last-known retention" }
            require(!(synthetic && live)) { "--synthetic and --live are mutually exclusive" }
            require(!forwardLive || live) { "--forward-live requires explicit --live mode" }
            require(!live || forwardLive) { "Explicit --live mode requires authenticated --forward-live transport" }
            require(!forwardSynthetic || synthetic) { "--forward-synthetic requires explicit --synthetic mode" }
            require(!(forwardLive && forwardSynthetic)) { "Live and synthetic forwarding are mutually exclusive" }
            require(!forwardSynthetic) { "DEMO/synthetic mode cannot forward to TAK" }
            val mode=environment.get("DRONK_MODE")
            require(mode == null || mode in setOf("DEMO","CAPTURE","LIVE")) { "Invalid DRONK mode" }
            require(mode != "CAPTURE" || !forwardLive) { "CAPTURE cannot forward to TAK" }
            require(mode != "DEMO" || (synthetic && !forwardLive)) { "DEMO cannot access receivers or TAK" }
            require(mode != "LIVE" || (live && forwardLive)) { "LIVE requires explicit forwarding" }
            if (forwardLive && (hostname.isBlank() || p12 == null || password == null || ca == null))
                throw BridgeFailure("E_CONFIG_INCOMPLETE")
            return BridgeConfig(synthetic, live, forwardLive, forwardSynthetic, provisional,
                java.time.Duration.ofSeconds(stale), hostname, port, p12, password, ca, connectAddress?.takeIf { it.isNotBlank() } ?: hostname, pilot,
                java.time.Duration.ofSeconds(lastKnown), lastKnownStyle)
        }

        private fun Array<String>.value(index: Int): String = getOrNull(index)
            ?: throw IllegalArgumentException("Missing option value")
    }
}

/** Bounded, source-shaped fixture. The same processor/parser/tracker/CoT path handles it as USB input. */
internal fun runSyntheticScenario(processor: LiveSerialProcessor, intervalMillis: Long = 1_000) {
    require(intervalMillis in 0..10_000)
    val testId = "SYN" + UUID.randomUUID().toString().replace("-", "").take(17)
    val positions = listOf(38.6270 to -90.1994, 38.6273 to -90.1990, 38.6276 to -90.1986)
    positions.forEachIndexed { index, (lat, lon) ->
        val line = """{"mac":"02:11:22:33:44:55","rssi":-61,"drone_lat":$lat,"drone_long":$lon,"drone_altitude":130,"pilot_lat":38.6300,"pilot_long":-90.2000,"basic_id":"$testId"}""" + "\n"
        processor.feed(line.toByteArray(Charsets.UTF_8), SerialContext(Instant.now(), ObservationSource.SIMULATION))
        if (index != positions.lastIndex && intervalMillis > 0) Thread.sleep(intervalMillis)
    }
}

internal fun tlsTransport(config: BridgeConfig): CotTransport {
    checkTlsFile(checkNotNull(config.passwordFile), true)
    checkTlsFile(checkNotNull(config.p12), true)
    checkTlsFile(checkNotNull(config.caFile), false)
    val password = try { readPassword(checkNotNull(config.passwordFile)) }
        catch (_: Exception) { throw BridgeFailure("E_PASSWORD_ENCODING") }
    try {
        val kmf = try {
            val clientStore = KeyStore.getInstance("PKCS12")
            Files.newInputStream(config.p12).use { clientStore.load(it, password) }
            KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm()).apply { init(clientStore, password) }
        } catch (_: Exception) { throw BridgeFailure("E_CLIENT_CREDENTIAL") }
        val tmf = try {
            val trustStore = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }
            val certificates = Files.newInputStream(config.caFile).use {
                CertificateFactory.getInstance("X.509").generateCertificates(it).filterIsInstance<X509Certificate>()
            }
            require(certificates.isNotEmpty() && certificates.size <= 32)
            certificates.forEachIndexed { index, certificate ->
                require(certificate.basicConstraints >= 0)
                certificate.checkValidity()
                trustStore.setCertificateEntry("trusted-ca-$index", certificate)
            }
            TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).apply { init(trustStore) }
        } catch (_: java.security.cert.CertificateExpiredException) { throw BridgeFailure("E_TLS_TRUST_EXPIRED") }
          catch (_: java.security.cert.CertificateNotYetValidException) { throw BridgeFailure("E_TLS_TRUST_EXPIRED") }
          catch (_: Exception) { throw BridgeFailure("E_TLS_TRUST") }
        val factory = SSLContext.getInstance("TLS").apply { init(kmf.keyManagers, tmf.trustManagers, null) }.socketFactory
        return org.ouitak.app.core.TakServerTlsTransport(config.hostname, config.port, { factory }, connectAddress=config.connectAddress)
    } finally { Arrays.fill(password, '\u0000') }
}

private fun checkTlsFile(path: Path, secret: Boolean) {
    if (!Files.isRegularFile(path) || !Files.isReadable(path)) throw BridgeFailure("E_CREDENTIAL_FILE")
    try {
        val permissions=Files.getPosixFilePermissions(path)
        if (secret && permissions.any { it.name.startsWith("GROUP_") || it.name.startsWith("OTHERS_") })
            throw BridgeFailure("E_CREDENTIAL_PERMS")
    } catch (_: UnsupportedOperationException) { /* Unix permission check is platform-specific. */ }
}

private fun readPassword(path: Path): CharArray {
    val raw = Files.readAllBytes(path)
    var size = raw.size
    var decoded: CharBuffer? = null
    while (size > 0 && (raw[size - 1] == '\n'.code.toByte() || raw[size - 1] == '\r'.code.toByte())) size--
    try {
        decoded = Charsets.UTF_8.newDecoder().onMalformedInput(CodingErrorAction.REPORT)
            .onUnmappableCharacter(CodingErrorAction.REPORT).decode(ByteBuffer.wrap(raw, 0, size))
        return CharArray(decoded.remaining()).also { decoded.get(it) }
    } catch (_: Exception) {
        throw IllegalArgumentException("Client password file is not valid UTF-8")
    } finally {
        decoded?.takeIf { it.hasArray() }?.let { Arrays.fill(it.array(), '\u0000') }
        Arrays.fill(raw, 0)
    }
}

private fun log(message: String) = println("${Instant.now()} $message")
